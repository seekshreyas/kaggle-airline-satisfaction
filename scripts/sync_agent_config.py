#!/usr/bin/env python3
"""Generate coding-tool adapters from shared repository instructions."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = "<!-- Generated by scripts/sync_agent_config.py; do not edit. -->"

# Source name -> file patterns used by each adapter.
SCOPES = {
    "python": "**/*.py",
    "sql": "**/*.sql",
    "notebooks": "notebooks/**",
}


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def markdown_body(path: Path) -> str:
    return read_text(path).strip() + "\n"


def build_outputs() -> dict[Path, str]:
    """Build all desired outputs before writing any files."""
    if not (ROOT / "AGENTS.md").is_file():
        raise ValueError("Missing AGENTS.md in the repository root.")

    outputs = {
        ROOT / "CLAUDE.md": f"{MARKER}\n\n@AGENTS.md\n",
        ROOT / "GEMINI.md": f"{MARKER}\n\n@AGENTS.md\n",
    }

    for name, pattern in SCOPES.items():
        source = ROOT / ".agents" / "instructions" / f"{name}.md"
        if not source.is_file():
            continue

        body = markdown_body(source)
        source_note = f"<!-- Source: {source.relative_to(ROOT).as_posix()} -->"
        # JSON string literals are also valid YAML quoted strings.
        quoted_pattern = json.dumps(pattern)

        copilot = (
            "---\n"
            f"applyTo: {quoted_pattern}\n"
            "---\n\n"
            f"{MARKER}\n"
            f"{source_note}\n\n"
            f"{body}"
        )
        cursor = (
            "---\n"
            f"description: {json.dumps(f'Shared {name} conventions')}\n"
            f"globs: {quoted_pattern}\n"
            "alwaysApply: false\n"
            "---\n\n"
            f"{MARKER}\n"
            f"{source_note}\n\n"
            f"{body}"
        )

        outputs[
            ROOT / ".github" / "instructions"
            / f"generated-{name}.instructions.md"
        ] = copilot
        outputs[
            ROOT / ".cursor" / "rules" / f"generated-{name}.mdc"
        ] = cursor

    return outputs


def existing_generated_rules() -> set[Path]:
    """Find only marked rule files belonging to this script."""
    locations = (
        (ROOT / ".github" / "instructions", "generated-*.instructions.md"),
        (ROOT / ".cursor" / "rules", "generated-*.mdc"),
    )
    owned = set()

    for directory, pattern in locations:
        for path in directory.glob(pattern):
            if not path.is_symlink() and MARKER in read_text(path):
                owned.add(path)

    return owned


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check generated files without modifying them.",
    )
    args = parser.parse_args()

    outputs = build_outputs()
    changed: list[Path] = []
    conflicts: list[Path] = []

    # Preflight all destinations before performing any writes.
    for path, desired in outputs.items():
        if path.is_symlink():
            conflicts.append(path)
            continue

        if not path.exists():
            changed.append(path)
            continue

        current = read_text(path)
        if MARKER not in current:
            conflicts.append(path)
        elif current != desired:
            changed.append(path)

    if conflicts:
        for path in conflicts:
            print(
                f"Refusing to overwrite unmanaged file: "
                f"{path.relative_to(ROOT)}",
                file=sys.stderr,
            )
        return 2

    stale = sorted(existing_generated_rules() - outputs.keys())

    if args.check:
        for path in changed:
            print(f"OUTDATED {path.relative_to(ROOT)}")
        for path in stale:
            print(f"STALE    {path.relative_to(ROOT)}")

        if changed or stale:
            return 1

        print("Agent configuration is up to date.")
        return 0

    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8")
        print(f"WROTE   {path.relative_to(ROOT)}")

    for path in stale:
        path.unlink()
        print(f"REMOVED {path.relative_to(ROOT)}")

    print(f"Updated {len(changed)} file(s); removed {len(stale)} stale file(s).")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        raise SystemExit(2)
